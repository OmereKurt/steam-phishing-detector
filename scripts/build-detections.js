#!/usr/bin/env node
"use strict";

/**
 * Generate SIEM detection content from the scorer.
 *
 *   npm run build:detections          write detections/
 *   npm run build:detections -- --check   fail if anything is stale
 *
 * WHY THIS IS A GENERATOR AND NOT A HAND-WRITTEN RULE
 *
 * src/scoring.js is a weighted accumulator. Sigma, SPL, KQL and XQL are
 * pattern matchers: they can test whether a field equals or contains a value,
 * not run Damerau-Levenshtein over it. A hand-written rule would therefore
 * drift from the scorer the first time a weight moved, and nothing would
 * notice. Generating from the same constants means `--check` fails CI instead.
 *
 * WHAT SURVIVES THE TRANSLATION, AND WHAT DOES NOT
 *
 * The scorer warns at 35. A pattern matcher has no notion of a running total,
 * so the only signals that can be expressed as a standalone rule are the ones
 * that reach 35 on their own:
 *
 *   edit_distance      40   expressible ONLY by materialising the neighbourhood.
 *                           src/permutations.js already generates it, so the
 *                           distance <= 2 set is emitted as a literal list.
 *   homoglyph          35   same approach, materialised from the generator.
 *   embedded_official  35   a substring test. Translates exactly.
 *
 * These do not reach 35 alone and are emitted as a separate, lower-confidence
 * rule covering only the pairs that do:
 *
 *   official_tld_swap  30 + login_keyword 10  = 40
 *   punycode           30 + login_keyword 10  = 40
 *   official_tld_swap  30 + risky_tld     10  = 40
 *
 * And one signal cannot cross at all:
 *
 *   branding           15   reads the page title and image alt text. That is
 *                           DOM state. It is not in a proxy log, and no
 *                           amount of query language will put it there.
 *
 * The credential-field gate is likewise unavailable, so the SIEM rules cannot
 * halve the score for a page with no password field. They will therefore fire
 * on lookalike domains that the extension would keep quiet about. That is a
 * real difference in behaviour, not a rounding error, and it is why coverage
 * is measured in test/detections.test.js rather than asserted here.
 */

const fs = require("fs");
const path = require("path");

const scoring = require("../src/scoring.js");
const detectionRule = require("../src/detection-rule.js");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "detections");

const CHECK = process.argv.includes("--check");

// ---------------------------------------------------------------------------
// Materialise the signals that need a value list
// ---------------------------------------------------------------------------

// Materialised by src/detection-rule.js so the generator and the tests that
// exercise the rule can never disagree about what is in it.
const lookalikes = detectionRule.materialiseLookalikes();
const lookalikeHosts = [...lookalikes.keys()];
const officialDomains = [...scoring.OFFICIAL_DOMAINS].sort();
const riskyTlds = [...scoring.RISKY_TLDS].sort();
const loginKeywords = ["login", "signin", "authenticate", "trade", "market"];
const officialLabels = officialDomains.map(d => d.split(".")[0]).sort();

const GENERATED = "Generated by scripts/build-detections.js -- do not edit by hand.";

// ---------------------------------------------------------------------------
// Sigma
// ---------------------------------------------------------------------------

/**
 * SigmaHQ indents with four spaces and quotes every value. Matching their
 * conventions here rather than reformatting at submission time means the file
 * in this repository is the file that would be proposed upstream.
 */
function yamlList(values, indent) {
  return values.map(v => `${indent}- '${String(v).replace(/'/g, "''")}'`).join("\n");
}

function sigmaHighConfidence() {
  return `# ${GENERATED}
title: Steam Credential Phishing Domain
id: 8f3c1d64-2a7e-4b19-9c05-6e1f2a7d4b83
status: experimental
description: |
    A web request to a hostname that impersonates a Steam sign-in domain, by
    typo, homoglyph, or by carrying an official Steam domain inside a hostname
    someone else controls. Each condition below reaches the scorer's warn
    threshold on its own; weaker signals are in the -low-confidence rule.
    The scorer's path and query embedding shapes are deliberately excluded:
    measured against the labelled corpus they add 2 detections and 6 false
    positives, because archives, URL scanners and translators all legitimately
    carry a Steam domain in a path or redirect parameter.
references:
    - https://github.com/OmereKurt/steam-phishing-detector
author: Omer Kurt
date: 2026-08-24
tags:
    - attack.credential-access
    - attack.initial-access
    - attack.t1566.002
logsource:
    category: proxy
detection:
    lookalike_host:
        cs-host:
${yamlList(lookalikeHosts, "            ")}
    embedded_official_host:
        cs-host|contains:
${yamlList(officialDomains.map(d => d + "."), "            ")}
    embedded_official_label:
        cs-host|contains:
${yamlList(officialLabels, "            ")}
    official_host:
        cs-host|endswith:
${yamlList(officialDomains, "            ")}
    condition: (lookalike_host or embedded_official_host or embedded_official_label) and not official_host
falsepositives:
    - Steam brand-protection domains that Valve registers defensively and then redirects
    - Fan sites and wikis whose hostname carries a Steam brand label, which the browser
      extension suppresses with a credential-field check that a proxy log cannot reproduce
level: high
`;
}

function sigmaLowConfidence() {
  return `# ${GENERATED}
title: Possible Steam Phishing Domain (Weak Signal Pair)
id: 5b90e7a2-41cf-4d8a-b3e6-90ac5d1f7e22
status: experimental
description: |
    Two signals that are individually below the scorer's warn threshold but
    reach it together: an official Steam label on a suffix Valve does not use,
    or an IDN label, paired with a credential or trading keyword in the URL.
    Expect more noise than the high-confidence rule; this is a hunting rule.
references:
    - https://github.com/OmereKurt/steam-phishing-detector
author: Omer Kurt
date: 2026-08-24
tags:
    - attack.credential-access
    - attack.initial-access
    - attack.t1566.002
logsource:
    category: proxy
detection:
    official_label:
        cs-host|startswith:
${yamlList(officialLabels.map(l => l + "."), "            ")}
    punycode_label:
        cs-host|contains: 'xn--'
    risky_tld:
        cs-host|endswith:
${yamlList(riskyTlds.map(t => "." + t), "            ")}
    keyword:
        c-uri|contains:
${yamlList(loginKeywords, "            ")}
    official_host:
        cs-host|endswith:
${yamlList(officialDomains, "            ")}
    condition: ((official_label or punycode_label) and (keyword or risky_tld)) and not official_host
falsepositives:
    - Legitimate internationalised domains that happen to sit on a page with a login path
level: medium
`;
}

// ---------------------------------------------------------------------------
// SIEM dialects
// ---------------------------------------------------------------------------

function officialRegexAlternation() {
  // Emits `steamcommunity\.com|steampowered\.com|...` -- one backslash, not two.
  return officialDomains.map(d => d.replace(/\./g, "\\.")).join("|");
}

function splunk() {
  return `# ${GENERATED}
# Splunk SPL -- Steam credential phishing domain
# ATT&CK T1566.002, T1656
#
# Prerequisite: publish detections/lookups/steam-lookalike-domains.csv as the
# lookup definition \`steam_lookalike_domains\` (fields: host, signal). The list
# is data and the rule is logic; do not paste ${lookalikeHosts.length} domains into the search.

index=proxy
| eval host=lower(cs_host), uri=lower(cs_uri)
\`\`\` official Steam domains short-circuit, exactly as the scorer allowlists them \`\`\`
| search NOT (${officialDomains.map(d => `host="${d}" OR host="*.${d}"`).join(" OR ")})
| lookup steam_lookalike_domains host OUTPUT signal AS lookalike_signal
| eval signal=case(
    isnotnull(lookalike_signal), "lookalike_domain",
    match(host, "(${officialRegexAlternation()})\\."), "embedded_official_host",
    match(host, "(${officialLabels.join("|")})"), "embedded_official_label",
    1=1, null())
| where isnotnull(signal)
| stats count AS hits, min(_time) AS first_seen, max(_time) AS last_seen, values(uri) AS uris
        BY host, src_ip, signal
| eval technique="T1566.002"
| sort - hits
`;
}

function sentinel() {
  return `// ${GENERATED}
// Microsoft Sentinel KQL -- Steam credential phishing domain
// ATT&CK T1566.002, T1656
//
// Prerequisite: upload detections/lookups/steam-lookalike-domains.csv as a
// watchlist aliased 'SteamLookalikeDomains' with 'host' as the search key.
// Written against CommonSecurityLog; repoint the table and the two column
// names for another proxy schema.

let OfficialDomains = dynamic([${officialDomains.map(d => `"${d}"`).join(", ")}]);
let OfficialPattern = @"(${officialRegexAlternation()})";
let Lookalikes = _GetWatchlist('SteamLookalikeDomains') | project host = tolower(tostring(host));
CommonSecurityLog
| where isnotempty(DestinationHostName) or isnotempty(RequestURL)
| extend Host = tolower(coalesce(DestinationHostName, tostring(parse_url(RequestURL).Host)))
| extend Uri = tolower(RequestURL)
// Last two labels, matching the scorer's own two-label registrable-domain
// approximation. Both share the same public-suffix limitation, deliberately.
| extend Registrable = strcat_array(array_slice(split(Host, "."), -2, -1), ".")
| where Registrable !in (OfficialDomains)
| extend Signal = case(
    Host in (Lookalikes), "lookalike_domain",
    Host matches regex strcat(OfficialPattern, @"\\."), "embedded_official_host",
    Host matches regex @"(${officialLabels.join("|")})", "embedded_official_label",
    "")
| where isnotempty(Signal)
| summarize Hits = count(), FirstSeen = min(TimeGenerated), LastSeen = max(TimeGenerated),
            Uris = make_set(Uri, 20) by Host, SourceIP, Signal
| extend Technique = "T1566.002"
| order by Hits desc
`;
}

function xql() {
  return `// ${GENERATED}
// Cortex XSIAM / XDR XQL -- Steam credential phishing domain
// ATT&CK T1566.002, T1656
//
// Prerequisite: load detections/lookups/steam-lookalike-domains.csv as the
// lookup dataset \`steam_lookalike_domains\` (fields: host, signal). Repoint the
// dataset and field names at whichever source carries your web traffic.

dataset = panw_ngfw_url_logs
| alter host = lowercase(url_domain), uri = lowercase(url_path)
| filter host != null
// official Steam domains short-circuit, exactly as the scorer allowlists them
| filter not (${officialDomains.map(d => `host = "${d}" or host ~= "\\.${d.replace(/\./g, "\\.")}$"`).join(" or ")})
| join type = left conflict_strategy = both (
    dataset = steam_lookalike_domains
    | fields host as lookalike_host, signal as lookalike_signal
  ) as lk lk.lookalike_host = host
| alter signal = if(
    lookalike_host != null, "lookalike_domain",
    host ~= "(${officialRegexAlternation()})\\.", "embedded_official_host",
    host ~= "(${officialLabels.join("|")})", "embedded_official_label",
    null)
| filter signal != null
| comp count() as hits, min(_time) as first_seen, max(_time) as last_seen by host, source_ip, signal
| alter technique = "T1566.002"
| sort desc hits
`;
}

function lookupCsv() {
  const rows = [...lookalikes].map(([host, signal]) => `${host},${signal}`);
  return `host,signal\n${rows.join("\n")}\n`;
}

// ---------------------------------------------------------------------------

const artefacts = {
  "steam-phishing-domain.sigma.yml": sigmaHighConfidence(),
  "steam-phishing-domain-low-confidence.sigma.yml": sigmaLowConfidence(),
  "splunk/steam-phishing-domain.spl": splunk(),
  "sentinel/steam-phishing-domain.kql": sentinel(),
  "cortex-xsiam/steam-phishing-domain.xql": xql(),
  "lookups/steam-lookalike-domains.csv": lookupCsv()
};

let stale = 0;
for (const [rel, content] of Object.entries(artefacts)) {
  const dest = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const current = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
  if (current === content) continue;
  if (CHECK) {
    console.error(`stale: detections/${rel}`);
    stale++;
  } else {
    fs.writeFileSync(dest, content);
    console.log(`wrote detections/${rel}`);
  }
}

if (CHECK) {
  if (stale) {
    console.error(`\n${stale} generated file(s) do not match src/. Run: npm run build:detections`);
    process.exit(1);
  }
  console.log(`detections/ is in sync with src/ (${lookalikeHosts.length} materialised hosts)`);
} else {
  console.log(`\n${lookalikeHosts.length} lookalike hosts materialised from src/permutations.js`);
}
